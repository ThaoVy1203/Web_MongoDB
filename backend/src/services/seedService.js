export const buildTimelineForStatus = (status, baseDate = new Date()) => {
  const stepMap = {
    "Tiếp nhận": 1,
    "Đang kiểm tra": 2,
    "Chờ linh kiện": 3,
    "Chờ duyệt": 3,
    "Đang sửa chữa": 4,
    "Đã sửa xong": 5,
    "Đã trả khách": 6,
    "Từ chối bảo hành": 2,
  };
  const current = stepMap[status] || 1;
  const defs = [
    {
      step: 1,
      title: "Tiếp nhận chứng từ & Thiết bị",
      desc: "Đối chiếu giấy bảo hành điện tử, số Serial và ghi nhận hiện trạng ngoại quan.",
    },
    {
      step: 2,
      title: "Chẩn đoán kỹ thuật chuyên sâu",
      desc: "Kỹ thuật viên đo kiểm phần cứng, xác định mã lỗi và nguyên nhân gốc.",
    },
    {
      step: 3,
      title: "Điều phối linh kiện & Phê duyệt",
      desc: "Xác thực quyền lợi gói bảo hành và xuất kho linh kiện OEM chính hãng.",
    },
    {
      step: 4,
      title: "Xử lý kỹ thuật & Thay thế module",
      desc: "Thực hiện thay thế linh kiện tiêu chuẩn phòng sạch ESD.",
    },
    {
      step: 5,
      title: "Kiểm định chất lượng (QC Pass)",
      desc: "Chạy bài stress-test hiệu năng, nhiệt độ và ổn định nguồn điện 100%.",
    },
    {
      step: 6,
      title: "Nghiệm thu & Bàn giao hoàn tất",
      desc: "Cập nhật biên bản điện tử vào sổ bảo hành số và hoàn trả thiết bị.",
    },
  ];

  return defs.map((d, idx) => {
    let state = "pending";
    if (status === "Đã trả khách") {
      state = "completed";
    } else if (d.step < current) {
      state = "completed";
    } else if (d.step === current) {
      state = "active";
    }
    return {
      step: d.step,
      title: d.title,
      description:
        status === "Từ chối bảo hành" && d.step === 2
          ? "Thiết bị vi phạm điều khoản loại trừ bảo hành miễn phí theo biên bản giám định."
          : d.desc,
      actor: d.step === 1 ? "Quầy Tiếp Nhận" : "Trung Tâm Kỹ Thuật WarrantyOps",
      state,
      timestamp: new Date(new Date(baseDate).getTime() + idx * 2 * 60 * 60 * 1000),
    };
  });
};

